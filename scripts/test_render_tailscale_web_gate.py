import argparse
import importlib.util
import pathlib
import stat
import subprocess
import sys
import tempfile
import unittest


ROOT = pathlib.Path(__file__).resolve().parent.parent
SCRIPT = ROOT / "scripts/render_tailscale_web_gate.py"


def load_renderer():
    spec = importlib.util.spec_from_file_location("render_tailscale_web_gate", SCRIPT)
    assert spec is not None
    module = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


renderer = load_renderer()


class TailscaleWebGateTest(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.root = pathlib.Path(self.temp.name)
        self.values = {
            "SWITCHYARD_WEB_BIND_HOST": "100.65.164.66",
            "SWITCHYARD_TAILSCALE_PROXY_IPV4": "100.77.128.80",
            "WEB_PORT": "8081",
            "SWITCHYARD_DOCKER_BRIDGE_SUBNET": "172.29.0.0/24",
            "SWITCHYARD_DOCKER_BRIDGE_GATEWAY": "172.29.0.1",
            "SWITCHYARD_DOCKER_BRIDGE_NAME": "switchyard0",
            "SWITCHYARD_WEB_CONTAINER_IPV4": "172.29.0.10",
        }

    def tearDown(self):
        self.temp.cleanup()

    @staticmethod
    def args(**overrides):
        values = {
            "destination": None,
            "proxy": None,
            "port": None,
            "subnet": None,
            "gateway": None,
            "bridge_name": None,
            "web_container": None,
        }
        values.update(overrides)
        return argparse.Namespace(**values)

    def test_renders_exact_pre_dnat_gate(self):
        config = renderer.config_from_inputs(self.args(), self.values)
        self.assertEqual(
            renderer.render(config),
            '''#!/usr/sbin/nft -f
# Generated by render_tailscale_web_gate.py. Do not edit.
# Docker bridge: 172.29.0.0/24; gateway: 172.29.0.1
destroy table inet switchyard_web_gate

table inet switchyard_web_gate {
    chain prerouting {
        type filter hook prerouting priority dstnat - 1; policy accept;
        iifname "tailscale0" ip saddr 100.77.128.80 ip daddr 100.65.164.66 tcp dport 8081 counter accept comment "allow Tailscale proxy to web"
        ip daddr 100.65.164.66 tcp dport 8081 counter drop comment "drop other ingress to web"
    }

    chain output {
        type filter hook output priority dstnat - 1; policy accept;
        ip daddr 100.65.164.66 tcp dport 8081 counter drop comment "drop local access to web"
    }
}
''',
        )

    def test_rejects_injection_and_non_cgnat_or_same_peers(self):
        cases = (
            {"destination": '100.65.164.66; flush ruleset'},
            {"proxy": '100.77.128.80\nflush ruleset'},
            {"destination": "192.168.1.10"},
            {"proxy": "10.0.0.2"},
            {"proxy": self.values["SWITCHYARD_WEB_BIND_HOST"]},
            {"destination": "fd7a:115c:a1e0::1"},
        )
        for overrides in cases:
            with self.subTest(overrides=overrides), self.assertRaises(renderer.GateError):
                renderer.config_from_inputs(self.args(**overrides), self.values)

    def test_rejects_invalid_port_subnet_and_gateway(self):
        cases = (
            {"port": "0"},
            {"port": "65536"},
            {"port": "80;drop"},
            {"subnet": "172.29.0.1/24"},
            {"subnet": "172.29.0.0/23"},
            {"subnet": "100.64.0.0/24"},
            {"subnet": "172.29.0.0/33"},
            {"gateway": "172.29.1.1"},
            {"gateway": "172.29.0.0"},
            {"gateway": "172.29.0.255"},
            {"bridge_name": "bad interface"},
            {"bridge_name": "interface-name-too-long"},
            {"web_container": "172.29.0.1"},
            {"web_container": "172.29.1.10"},
        )
        for overrides in cases:
            with self.subTest(overrides=overrides), self.assertRaises(renderer.GateError):
                renderer.config_from_inputs(self.args(**overrides), self.values)

    def test_dotenv_is_literal_strict_and_refuses_symlink(self):
        env_file = self.root / "gate.env"
        env_file.write_text(" export A = $OTHER # comment\nB='quoted'\n", encoding="utf-8")
        self.assertEqual(renderer.read_dotenv(env_file), {"A": "$OTHER", "B": "quoted"})

        duplicate = self.root / "duplicate.env"
        duplicate.write_text("A=one\nA=two\n", encoding="utf-8")
        with self.assertRaises(renderer.GateError):
            renderer.read_dotenv(duplicate)

        link = self.root / "linked.env"
        link.symlink_to(env_file)
        with self.assertRaises(renderer.GateError):
            renderer.read_dotenv(link)

    def test_atomic_output_is_private_replaces_regular_and_refuses_symlink(self):
        output = self.root / "web-gate.nft"
        renderer.write_atomic(output, "fresh\n")
        self.assertEqual(output.read_text(encoding="utf-8"), "fresh\n")
        self.assertEqual(stat.S_IMODE(output.stat().st_mode), 0o600)

        output.write_text("old", encoding="utf-8")
        output.chmod(0o644)
        renderer.write_atomic(output, "rules\n")
        self.assertEqual(output.read_text(encoding="utf-8"), "rules\n")
        self.assertEqual(stat.S_IMODE(output.stat().st_mode), 0o600)

        target = self.root / "target"
        target.write_text("keep", encoding="utf-8")
        output.unlink()
        output.symlink_to(target)
        with self.assertRaises(renderer.GateError):
            renderer.write_atomic(output, "clobber\n")
        self.assertTrue(output.is_symlink())
        self.assertEqual(target.read_text(encoding="utf-8"), "keep")

        output.unlink()
        output.mkdir()
        with self.assertRaises(renderer.GateError):
            renderer.write_atomic(output, "clobber\n")

        real_parent = self.root / "real-parent"
        real_parent.mkdir()
        linked_parent = self.root / "linked-parent"
        linked_parent.symlink_to(real_parent, target_is_directory=True)
        with self.assertRaises(renderer.GateError):
            renderer.write_atomic(linked_parent / "gate.nft", "rules\n")
        self.assertFalse((real_parent / "gate.nft").exists())

    def test_check_does_not_write_and_failures_do_not_clobber(self):
        env_file = self.root / "gate.env"
        env_file.write_text("\n".join(f"{key}={value}" for key, value in self.values.items()) + "\n")
        output = self.root / "web-gate.nft"
        checked = subprocess.run(
            [sys.executable, str(SCRIPT), "--env-file", str(env_file), "--output", str(output), "--check"],
            capture_output=True,
            text=True,
            check=False,
        )
        self.assertEqual(checked.returncode, 0, checked.stderr)
        self.assertFalse(output.exists())

        output.write_text("known-good\n", encoding="utf-8")
        env_file.write_text(env_file.read_text().replace("WEB_PORT=8081", "WEB_PORT=invalid"))
        failed = subprocess.run(
            [sys.executable, str(SCRIPT), "--env-file", str(env_file), "--output", str(output)],
            capture_output=True,
            text=True,
            check=False,
        )
        self.assertEqual(failed.returncode, 1)
        self.assertEqual(output.read_text(encoding="utf-8"), "known-good\n")

    def test_require_matching_output_fails_closed_for_mismatch_and_symlink(self):
        env_file = self.root / "gate.env"
        env_file.write_text("\n".join(f"{key}={value}" for key, value in self.values.items()) + "\n")
        output = self.root / "web-gate.nft"
        expected = renderer.render(renderer.config_from_inputs(self.args(), self.values))
        output.write_text(expected)
        matched = subprocess.run(
            [sys.executable, str(SCRIPT), "--env-file", str(env_file), "--require-matching-output", str(output)],
            capture_output=True, text=True, check=False,
        )
        self.assertEqual(matched.returncode, 0, matched.stderr)
        output.write_text("stale rules\n")
        mismatched = subprocess.run(
            [sys.executable, str(SCRIPT), "--env-file", str(env_file), "--require-matching-output", str(output)],
            capture_output=True, text=True, check=False,
        )
        self.assertEqual(mismatched.returncode, 1)
        target = self.root / "target"
        target.write_text(expected)
        output.unlink()
        output.symlink_to(target)
        linked = subprocess.run(
            [sys.executable, str(SCRIPT), "--env-file", str(env_file), "--require-matching-output", str(output)],
            capture_output=True, text=True, check=False,
        )
        self.assertEqual(linked.returncode, 1)

    def test_invalid_secret_value_is_not_printed(self):
        secret = "never-print-this-credential"
        env_file = self.root / "gate.env"
        values = dict(self.values)
        values["SWITCHYARD_WEB_BIND_HOST"] = secret
        env_file.write_text("\n".join(f"{key}={value}" for key, value in values.items()) + "\n")
        result = subprocess.run(
            [sys.executable, str(SCRIPT), "--env-file", str(env_file), "--check"],
            capture_output=True,
            text=True,
            check=False,
        )
        self.assertEqual(result.returncode, 1)
        self.assertNotIn(secret, result.stdout + result.stderr)
        self.assertIn("SWITCHYARD_WEB_BIND_HOST", result.stderr)

    def test_systemd_gate_blocks_docker_and_switchyard(self):
        gate = (ROOT / "deploy/switchyard-web-gate.service").read_text(encoding="utf-8")
        switchyard = (ROOT / "deploy/switchyard.service").read_text(encoding="utf-8")
        self.assertIn("Before=docker.service switchyard.service", gate)
        self.assertIn("After=ufw.service", gate)
        self.assertIn("Wants=ufw.service", gate)
        self.assertIn("__UFW_HELPER__ ensure --env-file __ENV_FILE__", gate)
        self.assertIn("ExecStartPre=/usr/bin/nft --check --file __NFT_RULES__", gate)
        self.assertIn("ExecStart=/usr/bin/nft --file __NFT_RULES__", gate)
        self.assertNotIn("ExecReload", gate)
        self.assertNotIn("ExecStop", gate)
        self.assertIn("Requires=docker.service switchyard-web-gate.service", switchyard)
        self.assertIn("After=docker.service switchyard-web-gate.service network-online.target", switchyard)
        guard = "--require-matching-output __NFT_RULES__"
        self.assertEqual(switchyard.count(guard), 2)
        self.assertEqual(switchyard.count("__UFW_HELPER__ verify-gate --env-file __ENV_FILE__"), 2)
        self.assertEqual(switchyard.count("docker-compose.yml stop web"), 2)
        self.assertNotIn("systemctl reload switchyard-web-gate.service", switchyard)


if __name__ == "__main__":
    unittest.main()
