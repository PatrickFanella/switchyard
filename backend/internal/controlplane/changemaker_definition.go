func shapeInt(value int) *int { return &value }

func changemakerSourceOutputShape() JSONShape {
	text := JSONShapeProperty{Type: "string"}
	count := JSONShapeProperty{Type: "integer"}
	return JSONShape{Type: "object", Description: "Collected source material for grounded drafting (source adapter outputs).", Properties: map[string]JSONShapeProperty{
		"adapter":             {Type: "string", Enum: []string{SourceAdapterGiteaActivity}},
		"status":              {Type: "string", Description: "complete, partial (some sources failed), or empty (no items).", Enum: []string{SourceStatusComplete, SourceStatusPartial, SourceStatusEmpty}},
		"item_count":          count,
		"source_count":        count,
		"failed_source_count": count,
		"omitted_item_count":  count,
		"window_start":        {Type: "string", MaxLength: shapeInt(32)},
		"window_end":          {Type: "string", MaxLength: shapeInt(32)},
		"content":             {Type: "string", Description: "Source items with citation IDs, passed to the drafting step."},
		"references":          {Type: "string", Description: "Markdown source list rendered by the adapter."},
		"failures":            text,
		"source_ids":          text,
		"items": {Type: "array", MaxItems: shapeInt(maxSourceMaxItems), Items: &JSONShapeProperty{Type: "object", Required: []string{"id", "source", "kind", "number", "url", "updated_at"}, Properties: map[string]JSONShapeProperty{
			"id": text, "source": text, "kind": text, "number": count, "title": text, "state": text, "url": text, "updated_at": text,
		}}},
		"evidence_sha256": {Type: "string", MaxLength: shapeInt(64)},
		"artifact_name":   text,
	}, Required: []string{"adapter", "status", "item_count", "source_count", "failed_source_count", "omitted_item_count", "window_start", "window_end", "content", "references", "failures", "source_ids", "items", "evidence_sha256", "artifact_name"}}
}

func changemakerDraftOutputShape() JSONShape {
	return JSONShape{Type: "object", Description: "Grounded draft and its citation check.", Properties: map[string]JSONShapeProperty{
		"content":              {Type: "string"},
		"content_sha256":       {Type: "string", MaxLength: shapeInt(64)},
		"generated":            {Type: "boolean", Description: "false when no sources were collected and the model was not called."},
		"grounding_item_count": {Type: "integer"},
		"cited_sources":        {Type: "string"},
		"unknown_citations":    {Type: "string"},
	}, Required: []string{"content", "content_sha256", "generated", "grounding_item_count", "cited_sources", "unknown_citations"}}
}

func changemakerAttachOutputShape() JSONShape {
	return JSONShape{Type: "object", Description: "Attached draft handoff for review and publication workflows.", Properties: map[string]JSONShapeProperty{
		"artifact_name":            {Type: "string"},
		"grounding_status":         {Type: "string", Enum: []string{SourceStatusComplete, SourceStatusPartial, SourceStatusEmpty}},
		"draft_generated":          {Type: "boolean"},
		"generated_content_sha256": {Type: "string", MaxLength: shapeInt(64)},
		"evidence_sha256":          {Type: "string", MaxLength: shapeInt(64)},
	}, Required: []string{"artifact_name", "grounding_status", "draft_generated", "generated_content_sha256", "evidence_sha256"}}
}

