// seedChangemakerDailyDigest installs the grounded definition when none is
// stored. A stored definition is upgraded only when it is still the untouched
// shipped version 1: the upgrade is a new version, so runs already created keep
// their pipeline snapshot, and POST .../rollback {"version": 1} restores the
// prompt-only pipeline. Operator edits and rollbacks raise the version and are
// never overwritten.
func seedChangemakerDailyDigest(store Store) error {
	existing, err := store.WorkflowDefinition(changemakerDailyDigestID)
	if err != nil && !errors.Is(err, ErrNotFound) {
		return err
	}
	if err == nil && !isUnmodifiedLegacyChangemakerDefinition(existing) {
		return nil
	}
	saved, err := store.UpsertWorkflowDefinition(changemakerDailyDigestDefinition())
	if err != nil {
		return err
	}
	if saved.Version > 1 {
		workflow := changemakerDailyDigestWorkflow()
		if current, ok := findWorkflow(store, changemakerDailyDigestID); ok {
			workflow.Status = current.Status
		}
		return store.UpsertWorkflow(workflow)
	}
	return nil
}

func isUnmodifiedLegacyChangemakerDefinition(definition WorkflowDefinition) bool {
	if definition.Version != 1 || !isActiveWorkflowDefinition(definition) {
		return false
	}
	stored, err := json.Marshal(definition.Pipeline)
	if err != nil {
		return false
	}
	legacy, err := json.Marshal(changemakerDailyDigestLegacyPipeline())
	return err == nil && string(stored) == string(legacy)
}

func findWorkflow(store Store, id string) (Workflow, bool) {
	for _, workflow := range store.ListWorkflows() {
		if workflow.ID == id {
			return workflow, true
		}
	}
	return Workflow{}, false
}
