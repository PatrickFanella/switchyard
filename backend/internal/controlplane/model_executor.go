type ModelMessage struct {
	Role       string `json:"role"`
	Content    string `json:"content,omitempty"`
	Name       string `json:"name,omitempty"`
	ToolCallID string `json:"tool_call_id,omitempty"`
	ToolCalls  []any  `json:"tool_calls,omitempty"`
}

type ModelRequest struct {
	Model      string         `json:"model"`
	Messages   []ModelMessage `json:"messages"`
	Tools      []any          `json:"tools,omitempty"`
	ToolChoice any            `json:"tool_choice,omitempty"`
	Options    map[string]any `json:"options,omitempty"`
	// RequestID carries caller correlation through compatibility layers. It is
	// optional for native callers and is generated by the broker when absent.
	RequestID string `json:"request_id,omitempty"`
}

type ModelResponse struct {
	Content        string
	ToolCalls      []any
	CorrelationIDs map[string]string
}

type ModelStreamEvent struct {
	Type           string
	Content        string
	Error          string
	Done           bool
	CorrelationIDs map[string]string
}

type ModelStreamer interface {
	Stream(ctx context.Context, request ModelRequest, emit func(ModelStreamEvent) error) (ModelResponse, error)
}

// ModelBroker is the Switchyard-native model generation contract.
//
// It is intentionally small while llama-line remains the transitional
// model-broker backend. OCQ remains the transitional OpenCode executor path.
// Workflow code should depend on this interface instead of calling a
// service-specific model client directly. Future broker features such as queue
// state, routing policy, upstream health, and cancellation handles should grow
// from this contract rather than from imported service boundaries.
type ModelBroker interface {
	Generate(ctx context.Context, request ModelRequest) (ModelResponse, error)
}

type ModelBrokerConfiguration interface {
	Configured() bool
}

// ModelExecutor is kept as a compatibility alias for existing workflow tests and
// call sites. New code should use ModelBroker terminology.
type ModelExecutor = ModelBroker

type EnvModelBroker struct {
	llamaLineBaseURL string
	llamaLineAPIKey  string
	ollamaBaseURL    string
	openCodeBaseURL  string
	openCodeUsername string
	openCodePassword string
	client           *http.Client
}

func NewEnvModelBroker() *EnvModelBroker {
	return &EnvModelBroker{
		llamaLineBaseURL: strings.TrimRight(os.Getenv("LLAMA_LINE_BASE_URL"), "/"),
		llamaLineAPIKey:  os.Getenv("LLAMA_LINE_API_KEY"),
		ollamaBaseURL:    strings.TrimRight(os.Getenv("OLLAMA_BASE_URL"), "/"),
		openCodeBaseURL:  strings.TrimRight(firstNonEmpty(os.Getenv("OPENCODE_SERVER_URL"), "http://opencode:4096"), "/"),
		openCodeUsername: os.Getenv("OPENCODE_SERVER_USERNAME"),
		openCodePassword: os.Getenv("OPENCODE_SERVER_PASSWORD"),
		client:           &http.Client{Timeout: modelBrokerTimeout()},
	}
}

func modelBrokerTimeout() time.Duration {
	if raw := strings.TrimSpace(os.Getenv("MODEL_BROKER_TIMEOUT")); raw != "" {
		if parsed, err := time.ParseDuration(raw); err == nil && parsed > 0 {
			return parsed
		}
	}
	return 10 * time.Minute
}

type modelBrokerRetryPolicy struct {
	Attempts int
	Backoff  time.Duration
}

type modelBrokerHTTPError struct {
	StatusCode int
	Status     string
}

func (e modelBrokerHTTPError) Error() string {
	return e.Status
}

func modelBrokerRetryPolicyFromEnv() modelBrokerRetryPolicy {
	attempts := 1
	if raw := strings.TrimSpace(os.Getenv("MODEL_BROKER_RETRY_ATTEMPTS")); raw != "" {
		if parsed, err := strconv.Atoi(raw); err == nil && parsed > 0 && parsed <= 5 {
			attempts = parsed
		}
	}
	backoff := 250 * time.Millisecond
	if raw := strings.TrimSpace(os.Getenv("MODEL_BROKER_RETRY_BACKOFF")); raw != "" {
		if parsed, err := time.ParseDuration(raw); err == nil && parsed >= 0 && parsed <= 10*time.Second {
			backoff = parsed
		}
	}
	return modelBrokerRetryPolicy{Attempts: attempts, Backoff: backoff}
}

func modelBrokerRetryableStatus(status int) bool {
	return status == http.StatusTooManyRequests || status == http.StatusBadGateway || status == http.StatusServiceUnavailable || status == http.StatusGatewayTimeout || status >= 500
}

func modelBrokerRetryableError(err error) bool {
	if err == nil || errors.Is(err, context.Canceled) || errors.Is(err, context.DeadlineExceeded) {
		return false
	}
	var httpErr modelBrokerHTTPError
	if errors.As(err, &httpErr) {
		return modelBrokerRetryableStatus(httpErr.StatusCode)
	}
	return true
}

// NewEnvModelExecutor preserves the previous constructor name while returning
// the native broker implementation.
func NewEnvModelExecutor() *EnvModelBroker {
	return NewEnvModelBroker()
}

func (e *EnvModelBroker) Generate(ctx context.Context, request ModelRequest) (response ModelResponse, err error) {
	backend := "opencode"
	if strings.EqualFold(strings.TrimSpace(os.Getenv("MODEL_BROKER_BACKEND")), "llama-line") {
		backend = "llama-line"
	} else if e.shouldGenerateViaOllama(request.Model) {
		backend = "ollama"
	}
	ctx, span := startControlPlaneSpan(ctx, "model_broker.generate",
		attribute.String("model", request.Model),
		attribute.String("backend", backend),
		attribute.String("request_id", request.RequestID),
	)
	defer func() {
		status := "completed"
		if err != nil {
			status = "failed"
		}
		finishControlPlaneSpan(span, status, err,
			attribute.String("model", request.Model),
			attribute.String("backend", backend),
			attribute.String("request_id", request.RequestID),
		)
	}()
	return e.generateWithRetry(ctx, backend, request)
}

func (e *EnvModelBroker) generateWithRetry(ctx context.Context, backend string, request ModelRequest) (ModelResponse, error) {
	policy := modelBrokerRetryPolicyFromEnv()
	var lastErr error
	for attempt := 1; attempt <= policy.Attempts; attempt++ {
		response, err := e.generateOnce(ctx, backend, request)
		if err == nil {
			if response.CorrelationIDs == nil {
				response.CorrelationIDs = map[string]string{}
			}
			response.CorrelationIDs["model_broker_attempts"] = fmt.Sprintf("%d", attempt)
			return response, nil
		}
		lastErr = err
		if !modelBrokerRetryableError(err) || attempt == policy.Attempts {
			break
		}
		timer := time.NewTimer(policy.Backoff * time.Duration(attempt))
		select {
		case <-ctx.Done():
			timer.Stop()
			return ModelResponse{}, ctx.Err()
		case <-timer.C:
		}
	}
	return ModelResponse{}, lastErr
}

func (e *EnvModelBroker) generateOnce(ctx context.Context, backend string, request ModelRequest) (ModelResponse, error) {
	switch backend {
	case "llama-line":
		if strings.TrimSpace(e.llamaLineBaseURL) == "" {
			return ModelResponse{}, fmt.Errorf("LLAMA_LINE_BASE_URL is not configured")
		}
		return e.generateViaLlamaLine(ctx, request)
	case "ollama":
		return e.generateViaOllama(ctx, request)
	default:
		return e.generateViaOpenCode(ctx, request)
	}
}

func (e *EnvModelBroker) Stream(ctx context.Context, request ModelRequest, emit func(ModelStreamEvent) error) (response ModelResponse, err error) {
	backend := "opencode"
	if strings.EqualFold(strings.TrimSpace(os.Getenv("MODEL_BROKER_BACKEND")), "llama-line") {
		backend = "llama-line"
	} else if e.shouldGenerateViaOllama(request.Model) {
		backend = "ollama"
	}
	ctx, span := startControlPlaneSpan(ctx, "model_broker.stream",
		attribute.String("model", request.Model),
		attribute.String("backend", backend),
		attribute.String("request_id", request.RequestID),
	)
	defer func() {
		status := "completed"
		if err != nil {
			status = "failed"
		}
		finishControlPlaneSpan(span, status, err,
			attribute.String("model", request.Model),
			attribute.String("backend", backend),
			attribute.String("request_id", request.RequestID),
		)
	}()
	if strings.EqualFold(strings.TrimSpace(os.Getenv("MODEL_BROKER_STREAMING")), "buffered") || strings.EqualFold(strings.TrimSpace(os.Getenv("MODEL_BROKER_STREAMING")), "disabled") {
		return e.streamBuffered(ctx, request, emit)
	}
	if backend == "llama-line" {
		return e.streamViaLlamaLine(ctx, request, emit)
	}
	if backend == "ollama" {
		return e.streamViaOllama(ctx, request, emit)
	}
	return e.streamBuffered(ctx, request, emit)
}

func (e *EnvModelBroker) StreamingMode(model string) string {
	if strings.EqualFold(strings.TrimSpace(os.Getenv("MODEL_BROKER_STREAMING")), "buffered") || strings.EqualFold(strings.TrimSpace(os.Getenv("MODEL_BROKER_STREAMING")), "disabled") {
		return "buffered"
	}
	if strings.EqualFold(strings.TrimSpace(os.Getenv("MODEL_BROKER_BACKEND")), "llama-line") || e.shouldGenerateViaOllama(model) {
		return "native"
	}
	return "buffered"
}

func (e *EnvModelBroker) streamBuffered(ctx context.Context, request ModelRequest, emit func(ModelStreamEvent) error) (ModelResponse, error) {
	response, err := e.Generate(ctx, request)
	if err != nil {
		return ModelResponse{}, err
	}
	if err := emit(ModelStreamEvent{Type: "content", Content: response.Content, CorrelationIDs: response.CorrelationIDs}); err != nil {
		return ModelResponse{}, err
	}
	if err := emit(ModelStreamEvent{Type: "done", Done: true, CorrelationIDs: response.CorrelationIDs}); err != nil {
		return ModelResponse{}, err
	}
	return response, nil
}

func (e *EnvModelBroker) shouldGenerateViaOllama(model string) bool {
	backend := strings.TrimSpace(os.Getenv("MODEL_BROKER_BACKEND"))
	if strings.EqualFold(backend, "ollama") {
		return true
	}
	if strings.TrimSpace(e.ollamaBaseURL) == "" {
		return false
	}
	name := strings.ToLower(strings.TrimSpace(trimModelProviderPrefix(model, "ollama")))
	if strings.HasPrefix(strings.ToLower(strings.TrimSpace(model)), "ollama/") {
		return true
	}
	for _, prefix := range strings.Split(firstNonEmpty(os.Getenv("MODEL_BROKER_OLLAMA_MODELS"), "llama,qwen,mistral,codellama,nomic-embed,bge,deepseek,gemma,phi,hermes"), ",") {
		prefix = strings.ToLower(strings.TrimSpace(prefix))
		if prefix != "" && strings.HasPrefix(name, prefix) {
			return true
		}
	}
	return false
}

func modelRequestBody(model string, messages []ModelMessage, stream bool, tools []any, toolChoice any, options map[string]any) map[string]any {
	body := map[string]any{"model": model, "stream": stream, "messages": messages}
	if len(tools) > 0 {
		body["tools"] = tools
	}
	if toolChoice != nil {
		body["tool_choice"] = toolChoice
	}
	if len(options) > 0 {
		body["options"] = options
	}
	return body
}

func (e *EnvModelBroker) generateViaLlamaLine(ctx context.Context, request ModelRequest) (ModelResponse, error) {
	baseURL := e.llamaLineBaseURL
	endpoint, err := url.JoinPath(baseURL, "/v1/chat/completions")
	if err != nil {
		return ModelResponse{}, err
	}
	body, err := json.Marshal(modelRequestBody(request.Model, request.Messages, false, request.Tools, request.ToolChoice, request.Options))
	if err != nil {
		return ModelResponse{}, err
	}
	req, err := http.NewRequestWithContext(ctx, http.MethodPost, endpoint, bytes.NewReader(body))
	if err != nil {
		return ModelResponse{}, err
	}
	req.Header.Set("Content-Type", "application/json")
	if strings.TrimSpace(request.RequestID) != "" {
		req.Header.Set("X-Request-ID", request.RequestID)
		req.Header.Set("X-Llama-Line-Request-ID", request.RequestID)
	}
	if e.llamaLineAPIKey != "" {
		req.Header.Set("Authorization", "Bearer "+e.llamaLineAPIKey)
	}
	resp, err := e.client.Do(req)
	if err != nil {
		return ModelResponse{}, err
	}
	defer resp.Body.Close()
	if resp.StatusCode < 200 || resp.StatusCode > 299 {
		return ModelResponse{}, modelBrokerHTTPError{StatusCode: resp.StatusCode, Status: "model request failed: " + resp.Status}
	}
	bodyBytes, err := io.ReadAll(resp.Body)
	if err != nil {
		return ModelResponse{}, err
	}
	decoded, err := decodeModelBrokerChatResponse(bodyBytes)
	if err != nil {
		return ModelResponse{}, err
	}
	if len(decoded.Choices) == 0 {
		return ModelResponse{}, fmt.Errorf("model response contained no choices")
	}
	correlation := map[string]string{"model_broker": "switchyard", "model_source": "llama-line", "model_broker_backend": "compat"}
	if requestID := resp.Header.Get("X-Llama-Line-Request-ID"); requestID != "" {
		correlation["llama_line_request_id"] = requestID
	}
	if requestID := resp.Header.Get("X-OCQ-Request-ID"); requestID != "" {
		correlation["ocq_request_id"] = requestID
	}
	if sessionID := resp.Header.Get("X-OCQ-Session"); sessionID != "" {
		correlation["ocq_session_id"] = sessionID
	}
	return ModelResponse{Content: decoded.Choices[0].Message.Content, CorrelationIDs: correlation}, nil
}

func (e *EnvModelBroker) generateViaOllama(ctx context.Context, request ModelRequest) (ModelResponse, error) {
	if strings.TrimSpace(e.ollamaBaseURL) == "" {
		return ModelResponse{}, fmt.Errorf("OLLAMA_BASE_URL is not configured")
	}
	endpoint, err := url.JoinPath(e.ollamaBaseURL, "/api/chat")
	if err != nil {
		return ModelResponse{}, err
	}
	body, err := json.Marshal(modelRequestBody(ollamaModelName(request.Model), request.Messages, false, request.Tools, request.ToolChoice, request.Options))
	if err != nil {
		return ModelResponse{}, err
	}
	req, err := http.NewRequestWithContext(ctx, http.MethodPost, endpoint, bytes.NewReader(body))
	if err != nil {
		return ModelResponse{}, err
	}
	req.Header.Set("Content-Type", "application/json")
	if strings.TrimSpace(request.RequestID) != "" {
		req.Header.Set("X-Request-ID", request.RequestID)
	}
	resp, err := e.client.Do(req)
	if err != nil {
		return ModelResponse{}, err
	}
	defer resp.Body.Close()
	if resp.StatusCode < 200 || resp.StatusCode > 299 {
		return ModelResponse{}, modelBrokerHTTPError{StatusCode: resp.StatusCode, Status: "ollama request failed: " + resp.Status}
	}
	var decoded struct {
		Message struct {
			Content   string `json:"content"`
			ToolCalls []any  `json:"tool_calls"`
		} `json:"message"`
		Response string `json:"response"`
	}
	if err := json.NewDecoder(resp.Body).Decode(&decoded); err != nil {
		return ModelResponse{}, err
	}
	content := firstNonEmpty(decoded.Message.Content, decoded.Response)
	if strings.TrimSpace(content) == "" && len(decoded.Message.ToolCalls) == 0 {
		return ModelResponse{}, fmt.Errorf("ollama response did not include content")
	}
	return ModelResponse{Content: content, ToolCalls: decoded.Message.ToolCalls, CorrelationIDs: map[string]string{"model_broker": "switchyard", "model_source": "ollama", "model_broker_backend": "native", "ollama_model": ollamaModelName(request.Model)}}, nil
}

func (e *EnvModelBroker) streamViaOllama(ctx context.Context, request ModelRequest, emit func(ModelStreamEvent) error) (ModelResponse, error) {
	if strings.TrimSpace(e.ollamaBaseURL) == "" {
		return ModelResponse{}, fmt.Errorf("OLLAMA_BASE_URL is not configured")
	}
	endpoint, err := url.JoinPath(e.ollamaBaseURL, "/api/chat")
	if err != nil {
		return ModelResponse{}, err
	}
	body, err := json.Marshal(modelRequestBody(ollamaModelName(request.Model), request.Messages, true, request.Tools, request.ToolChoice, request.Options))
	if err != nil {
		return ModelResponse{}, err
	}
	req, err := http.NewRequestWithContext(ctx, http.MethodPost, endpoint, bytes.NewReader(body))
	if err != nil {
		return ModelResponse{}, err
	}
	req.Header.Set("Content-Type", "application/json")
	if strings.TrimSpace(request.RequestID) != "" {
		req.Header.Set("X-Request-ID", request.RequestID)
	}
	resp, err := e.client.Do(req)
	if err != nil {
		return ModelResponse{}, err
	}
	defer resp.Body.Close()
	if resp.StatusCode < 200 || resp.StatusCode > 299 {
		return ModelResponse{}, modelBrokerHTTPError{StatusCode: resp.StatusCode, Status: "ollama request failed: " + resp.Status}
	}
	correlation := map[string]string{"model_broker": "switchyard", "model_source": "ollama", "model_broker_backend": "native", "ollama_model": ollamaModelName(request.Model)}
	var builder strings.Builder
	scanner := bufio.NewScanner(resp.Body)
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		if line == "" {
			continue
		}
		var decoded struct {
			Message struct {
				Content string `json:"content"`
			} `json:"message"`
			Response string `json:"response"`
			Done     bool   `json:"done"`
			Error    string `json:"error"`
		}
		if err := json.Unmarshal([]byte(line), &decoded); err != nil {
			return ModelResponse{}, err
		}
		if decoded.Error != "" {
			return ModelResponse{}, errors.New(decoded.Error)
		}
		chunk := firstNonEmpty(decoded.Message.Content, decoded.Response)
		if chunk != "" {
			builder.WriteString(chunk)
			if err := emit(ModelStreamEvent{Type: "content", Content: chunk, CorrelationIDs: correlation}); err != nil {
				return ModelResponse{}, err
			}
		}
		if decoded.Done {
			break
		}
	}
	if err := scanner.Err(); err != nil {
		return ModelResponse{}, err
	}
	if err := emit(ModelStreamEvent{Type: "done", Done: true, CorrelationIDs: correlation}); err != nil {
		return ModelResponse{}, err
	}
	return ModelResponse{Content: builder.String(), CorrelationIDs: correlation}, nil
}

func (e *EnvModelBroker) streamViaLlamaLine(ctx context.Context, request ModelRequest, emit func(ModelStreamEvent) error) (ModelResponse, error) {
	if strings.TrimSpace(e.llamaLineBaseURL) == "" {
		return ModelResponse{}, fmt.Errorf("LLAMA_LINE_BASE_URL is not configured")
	}
	endpoint, err := url.JoinPath(e.llamaLineBaseURL, "/v1/chat/completions")
	if err != nil {
		return ModelResponse{}, err
	}
	body, err := json.Marshal(modelRequestBody(request.Model, request.Messages, true, request.Tools, request.ToolChoice, request.Options))
	if err != nil {
		return ModelResponse{}, err
	}
	req, err := http.NewRequestWithContext(ctx, http.MethodPost, endpoint, bytes.NewReader(body))
	if err != nil {
		return ModelResponse{}, err
	}
	req.Header.Set("Content-Type", "application/json")
	if strings.TrimSpace(request.RequestID) != "" {
		req.Header.Set("X-Request-ID", request.RequestID)
		req.Header.Set("X-Llama-Line-Request-ID", request.RequestID)
	}
	if e.llamaLineAPIKey != "" {
		req.Header.Set("Authorization", "Bearer "+e.llamaLineAPIKey)
	}
	resp, err := e.client.Do(req)
	if err != nil {
		return ModelResponse{}, err
	}
	defer resp.Body.Close()
	if resp.StatusCode < 200 || resp.StatusCode > 299 {
		return ModelResponse{}, modelBrokerHTTPError{StatusCode: resp.StatusCode, Status: "model request failed: " + resp.Status}
	}
	correlation := map[string]string{"model_broker": "switchyard", "model_source": "llama-line", "model_broker_backend": "compat"}
	if requestID := resp.Header.Get("X-Llama-Line-Request-ID"); requestID != "" {
		correlation["llama_line_request_id"] = requestID
	}
	if requestID := resp.Header.Get("X-OCQ-Request-ID"); requestID != "" {
		correlation["ocq_request_id"] = requestID
	}
	if sessionID := resp.Header.Get("X-OCQ-Session"); sessionID != "" {
		correlation["ocq_session_id"] = sessionID
	}
	var builder strings.Builder
	scanner := bufio.NewScanner(resp.Body)
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		if line == "" || strings.HasPrefix(line, ":") || strings.HasPrefix(line, "event:") {
			continue
		}
		if !strings.HasPrefix(line, "data:") {
			continue
		}
		payload := strings.TrimSpace(strings.TrimPrefix(line, "data:"))
		if payload == "[DONE]" {
			break
		}
		chunk := openAIStreamPayloadContent(payload)
		if chunk == "" {
			continue
		}
		builder.WriteString(chunk)
		if err := emit(ModelStreamEvent{Type: "content", Content: chunk, CorrelationIDs: correlation}); err != nil {
			return ModelResponse{}, err
		}
	}
	if err := scanner.Err(); err != nil {
		return ModelResponse{}, err
	}
	if err := emit(ModelStreamEvent{Type: "done", Done: true, CorrelationIDs: correlation}); err != nil {
		return ModelResponse{}, err
	}
	return ModelResponse{Content: builder.String(), CorrelationIDs: correlation}, nil
}

func openAIStreamPayloadContent(payload string) string {
	var decoded struct {
		Choices []struct {
			Delta struct {
				Content string `json:"content"`
			} `json:"delta"`
			Message struct {
				Content string `json:"content"`
			} `json:"message"`
			Text string `json:"text"`
		} `json:"choices"`
	}
	if err := json.Unmarshal([]byte(payload), &decoded); err != nil || len(decoded.Choices) == 0 {
		return ""
	}
	return firstNonEmpty(decoded.Choices[0].Delta.Content, decoded.Choices[0].Message.Content, decoded.Choices[0].Text)
}

func ollamaModelName(model string) string {
	return trimModelProviderPrefix(model, "ollama")
}

func trimModelProviderPrefix(model string, provider string) string {
	trimmed := strings.TrimSpace(model)
	prefix := provider + "/"
	if strings.HasPrefix(strings.ToLower(trimmed), strings.ToLower(prefix)) {
		return strings.TrimSpace(trimmed[len(prefix):])
	}
	return trimmed
}

func (e *EnvModelBroker) generateViaOpenCode(ctx context.Context, request ModelRequest) (ModelResponse, error) {
	executor := &EnvOpenCodeExecutor{baseURL: e.openCodeBaseURL, username: e.openCodeUsername, password: e.openCodePassword, client: e.client}
	prompt := modelMessagesToPrompt(request.Messages)
	requestID := firstNonEmpty(strings.TrimSpace(request.RequestID), "model-broker-"+shortRandomID())
	response, err := executor.SendPrompt(ctx, OpenCodeRequest{Model: request.Model, Prompt: prompt, RequestID: requestID, WorkDir: firstNonEmpty(os.Getenv("MODEL_BROKER_WORKDIR"), os.Getenv("OCQ_DEFAULT_DIRECTORY"), "/workspace")})
	if err != nil {
		return ModelResponse{}, err
	}
	correlation := cloneMap(response.CorrelationIDs)
	if correlation == nil {
		correlation = map[string]string{}
	}
	correlation["model_broker"] = "switchyard"
	correlation["model_source"] = "opencode"
	correlation["model_broker_backend"] = "native"
	return ModelResponse{Content: response.Content, CorrelationIDs: correlation}, nil
}

func modelMessagesToPrompt(messages []ModelMessage) string {
	var builder strings.Builder
	for _, message := range messages {
		content := strings.TrimSpace(message.Content)
		if content == "" {
			continue
		}
		role := strings.TrimSpace(message.Role)
		if role == "" {
			role = "user"
		}
		if builder.Len() > 0 {
			builder.WriteString("\n\n")
		}
		builder.WriteString(strings.ToUpper(role[:1]) + strings.ToLower(role[1:]) + ":\n")
		builder.WriteString(content)
	}
	return builder.String()
}

type modelBrokerChatResponse struct {
	Choices []struct {
		Message struct {
			Content string `json:"content"`
		} `json:"message"`
	} `json:"choices"`
}

func decodeModelBrokerChatResponse(body []byte) (modelBrokerChatResponse, error) {
	trimmed := strings.TrimSpace(string(body))
	if strings.HasPrefix(trimmed, "data:") {
		var completion string
		var lastStatus string
		for _, line := range strings.Split(trimmed, "\n") {
			line = strings.TrimSpace(line)
			if line == "" || strings.HasPrefix(line, ":") {
				continue
			}
			if strings.HasPrefix(line, "data:") {
				payload := strings.TrimSpace(strings.TrimPrefix(line, "data:"))
				if payload == "[DONE]" {
					break
				}
				if strings.Contains(payload, `"choices"`) {
					completion = payload
				} else if payload != "" {
					lastStatus = payload
				}
			}
		}
		if completion != "" {
			trimmed = completion
		} else if lastStatus != "" {
			return modelBrokerChatResponse{}, fmt.Errorf("model broker stream ended without chat completion; last event: %s", lastStatus)
		} else {
			return modelBrokerChatResponse{}, errors.New("model broker stream ended without chat completion")
		}
	}
	var decoded modelBrokerChatResponse
	if err := json.Unmarshal([]byte(trimmed), &decoded); err != nil {
		return modelBrokerChatResponse{}, err
	}
	return decoded, nil
}

func (e *EnvModelBroker) Configured() bool {
	if strings.EqualFold(strings.TrimSpace(os.Getenv("MODEL_BROKER_BACKEND")), "llama-line") {
		return strings.TrimSpace(e.llamaLineBaseURL) != ""
	}
	if strings.EqualFold(strings.TrimSpace(os.Getenv("MODEL_BROKER_BACKEND")), "ollama") {
		return strings.TrimSpace(e.ollamaBaseURL) != ""
	}
	return strings.TrimSpace(e.openCodeBaseURL) != ""
}
